#!/usr/bin/env python3
"""
Generate embedded font sources from VLW files.

  assets/fonts/<Name>.vlw  ->  src/vlw/<Name>.cpp      (one array per file, so the
                                                       linker drops unused sizes)
                           ->  src/EcamFontsData.h    (declarations for all fonts)

Run from the library root after adding/changing a .vlw:
  python3 tools/vlw2h.py

Generated files are committed so library users never need Python.
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
ASSETS = ROOT / "assets" / "fonts"
OUT_DIR = ROOT / "src" / "vlw"
HEADER = ROOT / "src" / "EcamFontsData.h"
NAMESPACE = "ecam_fonts::vlw"
BYTES_PER_LINE = 16
USAGE_SYM = "ECAMFontRegular16"

HEADER_NOTE = "// Generated by tools/vlw2h.py from assets/fonts - do not edit.\n"


def symbol(path: pathlib.Path) -> str:
    name = re.sub(r"\W", "_", path.stem)
    if name[0].isdigit():
        name = "_" + name
    return name


def natural_key(path: pathlib.Path):
    return [int(t) if t.isdigit() else t for t in re.split(r"(\d+)", path.stem)]


def write_cpp(vlw: pathlib.Path, sym: str) -> int:
    data = vlw.read_bytes()
    lines = []
    for i in range(0, len(data), BYTES_PER_LINE):
        lines.append("  " + ",".join(f"0x{b:02x}" for b in data[i:i + BYTES_PER_LINE]) + ",")
    body = "\n".join(lines)
    (OUT_DIR / f"{sym}.cpp").write_text(
        HEADER_NOTE
        + f'#include "{HEADER.name}"\n\n'
        + f"namespace {NAMESPACE} {{\n"
        + f"// {vlw.name}, {len(data)} bytes\n"
        + f"extern const uint8_t {sym}[] = {{\n{body}\n}};\n"
        + f"extern const size_t {sym}_size = sizeof({sym});\n"
        + "}\n"
    )
    return len(data)


def main():
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for old in OUT_DIR.glob("*.cpp"):
        old.unlink()

    fonts = sorted(ASSETS.glob("*.vlw"), key=natural_key)
    decls = []
    total = 0
    for vlw in fonts:
        sym = symbol(vlw)
        size = write_cpp(vlw, sym)
        total += size
        decls.append(f"extern const uint8_t {sym}[];  // {size} bytes\n"
                     f"extern const size_t  {sym}_size;")

    HEADER.write_text(
        "#pragma once\n"
        + HEADER_NOTE
        + "//\n"
        + "// VLW smooth fonts embedded in flash (zero RAM, no filesystem needed).\n"
        + f"// Usage: canvas.loadFont({NAMESPACE}::{USAGE_SYM});\n"
        + "#include <stdint.h>\n#include <stddef.h>\n\n"
        + f"namespace {NAMESPACE} {{\n"
        + "\n".join(decls)
        + "\n}\n"
    )
    print(f"Generated {len(fonts)} fonts, {total} bytes total")


if __name__ == "__main__":
    main()
